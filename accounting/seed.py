def seed(Account, AccountMapping):
    by = {}
    for code, name, typ, parent, grp in ACCOUNTS:
        a, _ = Account.objects.get_or_create(code=code, defaults={
            'name': name, 'account_type': typ, 'is_group': grp, 'is_system': code in SYSTEM,
            'parent': by.get(parent) if parent else None})
        by[code] = a
    for key, code, desc in MAPPINGS:
        AccountMapping.objects.get_or_create(key=key, defaults={'account': by.get(code) or Account.objects.get(code=code),
                                                                'description': desc})
